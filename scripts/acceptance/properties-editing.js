/**
 * [INPUT]: 隔离 Electron 临时库；属性插件、文件写回、types.json 和重启阶段。
 * [OUTPUT]: {pass,count,checks}，覆盖类型、菜单、侧栏编辑、真实写盘与重启读回。
 * [POS]: 属性系统交互验收；通过 run.mjs --no-screenshot 执行，verify 阶段复用已标记临时库。
 * [PROTOCOL]: 变更时更新此头部，然后检查 CLAUDE.md
 */
(async () => {
  const checks = [];
  const check = (value, message) => { if (!value) throw Error(message); checks.push(message); };
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const until = async (fn, message) => { for (let i = 0; i < 160; i++) { if (await fn()) return; await wait(25); } throw Error(message); };
  const fs = require('fs');
  const path = require('path');
  const yaml = require('js-yaml');
  await app.plugins.enableInternalPlugin('properties');
  const types = app.metadataTypeManager;
  check(!!types, '库级属性类型服务已初始化');
  const configPath = path.join(app.vaultPath, '.obsidian/types.json');
  const readConfig = () => JSON.parse(fs.readFileSync(configPath, 'utf8'));
  const diskFm = async file => yaml.load((await app.vault.read(file)).match(/^---\n([\s\S]*?)\n---/)[1], { schema: yaml.JSON_SCHEMA });
  if (process.env.OBS_RECOVERY_PHASE === 'verify') {
    check(types.getAssignedWidget('ScOrE') === 'number', '重启按忽略大小写的键读取 Number 类型');
    check(types.getAssignedWidget('status') === null, '重启保留 Automatic 类型');
    const config = readConfig();
    check(config.customFuture.token === 'preserve', '重启保留未知顶层配置');
    check(config.types.vendorField === 'future-widget', '重启保留未知类型');
    const file = app.vault.getFileByPath('Properties.md');
    const fm = await diskFm(file);
    check(fm.score === 17.5 && typeof fm.score === 'number', '重启真实读回侧栏数值');
    check(fm.title === 'Changed via sidebar', '重启真实读回侧栏文本');
    check(fm.flag === true, '重启真实读回复选框');
    check(JSON.stringify(fm.items) === '["alpha","beta"]', '重启真实读回列表且 Enter/blur 不重复');
    check(fm.renamed === 'Rename me' && !Object.hasOwn(fm, 'renameMe'), '重启真实读回重命名属性');
    check(fm.date === '2026-10-22' || fm.date?.toISOString?.().startsWith('2026-10-22'), '重启真实读回日期');
    return { pass: true, count: checks.length, checks };
  }
  fs.writeFileSync(configPath, JSON.stringify({ customFuture: { token: 'preserve' }, types: { vendorField: 'future-widget' } }));
  types.loadData();
  const file = await app.vault.create('Properties.md', '---\ntitle: Original\nscore: 3\nstatus: open\nflag: false\nitems: [alpha]\nrenameMe: Rename me\ndate: 2026-10-21\ntags: [one]\n---\n# Body remains\n');
  await app.workspace.openFile(file);
  await until(() => app.metadataCache.getFileCache(file)?.frontmatter?.score === 3, '属性元数据完成索引');
  const leaf = await app.workspace.ensureSideLeaf('file-properties', 'right', { reveal: true });
  const view = leaf.view;
  const row = key => view.contentEl.querySelector('.metadata-property[data-property-key="' + key + '"]');
  const input = key => row(key)?.querySelector('.metadata-property-value input,.metadata-property-value [contenteditable="true"]');
  await until(() => !!input('title'), '侧栏属性编辑器已挂载');
  check(input('title').isContentEditable, 'file-properties 侧栏提供可编辑文本输入');
  const edit = async (key, value) => {
    const target = input(key);
    target.focus(); if (target.isContentEditable) target.textContent = value; else target.value = value;
    target.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    target.blur();
    await until(async () => String((await diskFm(file))[key]) === value, '侧栏保存 ' + key);
    await wait(180);
  };
  await edit('title', 'Changed via sidebar');
  check((await diskFm(file)).title === 'Changed via sidebar', '侧栏文本修改真实落盘');
  await edit('title', 'Changed\nvia sidebar');
  check((await diskFm(file)).title === 'Changed\nvia sidebar', '原版 contenteditable 文本控件保留多行属性');
  await edit('title', 'Changed via sidebar');
  await edit('score', '17.5');
  check((await diskFm(file)).score === 17.5, '侧栏数值保存为 YAML number');
  row('flag').querySelector('.metadata-input-checkbox').click();
  await until(async () => (await diskFm(file)).flag === true, '等待复选框落盘');
  check((await diskFm(file)).flag === true, '侧栏复选框保存布尔值');
  await wait(180);
  const listInput = row('items').querySelector('.multi-select-input');
  listInput.focus(); listInput.value = 'beta';
  listInput.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
  listInput.blur();
  await until(async () => (await diskFm(file)).items.length === 2, '列表新增落盘');
  check(JSON.stringify((await diskFm(file)).items) === '["alpha","beta"]', '列表 Enter 后 blur 仅新增一次');
  await wait(180);
  const rename = row('renameMe').querySelector('.metadata-property-key-input');
  rename.value = 'renamed'; await rename.commitMetadata();
  await until(() => !!row('renamed'), '属性重命名重绘');
  check((await diskFm(file)).renamed === 'Rename me', '侧栏属性重命名保持原值');
  check(!Object.hasOwn(await diskFm(file), 'renameMe'), '旧属性键从 YAML 移除');
  const duplicate = row('renamed').querySelector('.metadata-property-key-input');
  duplicate.value = 'TITLE'; await duplicate.commitMetadata();
  check(duplicate.getAttribute('aria-invalid') === 'true', '拒绝忽略大小写的重复属性键');
  check((await diskFm(file)).title === 'Changed via sidebar', '拒绝重复键后保留原属性');
  duplicate.value = 'renamed';
  await types.setType('score', 'number');
  check(types.getAssignedWidget('SCORE') === 'number', '属性赋值忽略大小写');
  check(readConfig().types.score === 'number', 'Number 类型写入原版 types.json 格式');
  check(types.getTypeInfo('score', null).inferred.type === 'number', '空值仍使用显式 Number 类型');
  check(types.getTypeInfo('title', {}).inferred.type === 'unknown', '对象值明确显示 Unknown');
  check(types.getWidget('date').validate('2024-02-29'), '日期类型接受闰年合法日期');
  check(!types.getWidget('date').validate('2026-02-29'), '日期类型拒绝非闰年无效日期');
  check(types.getWidget('datetime').validate('2026-10-22T12:34'), '日期时间类型接受分钟格式');
  check(!types.getWidget('number').validate(NaN), 'Number 类型拒绝非有限数值');
  const externalConfig = readConfig();
  externalConfig.types.score = 'text';
  fs.writeFileSync(configPath, JSON.stringify(externalConfig));
  await until(() => types.getAssignedWidget('score') === 'text', '外部 types.json 更新同步');
  check(types.getAssignedWidget('score') === 'text', '文件监听同步其他窗口属性类型更新');
  await types.setType('score', 'number');
  check(readConfig().customFuture.token === 'preserve', '类型写回保留未知顶层键');
  check(readConfig().types.vendorField === 'future-widget', '类型写回保留未知类型');
  check(types.getWidget('future-widget').type === 'unknown', '未知类型明确退回 Unknown 控件');
  await types.setType('tags', 'number');
  check(types.getAssignedWidget('tags') === 'tags', '保留 tags 类型不可改为 Number');
  const before = await app.vault.read(file);
  await types.setType('status', 'number');
  check(await app.vault.read(file) === before, '类型赋值不静默转换不兼容值');
  check(types.getTypeInfo('status', 'open').expected.type === 'number', '不兼容值保留 Number 预期类型');
  check(types.getTypeInfo('status', 'open').inferred.type === 'text', '不兼容值保留 Text 编辑器');
  check(!!row('status').querySelector('.metadata-property-warning-icon'), '不兼容值显示类型警告');
  await types.unsetType('status');
  check(!row('status').querySelector('.metadata-property-warning-icon'), '切回 Automatic 移除类型警告');
  check(!Object.hasOwn(readConfig().types, 'status'), 'Automatic 从 types.json 删除赋值');
  const titleInput = input('title');
  const select = (target, from, to) => {
    target.focus();
    if (!target.isContentEditable) { target.setSelectionRange(from, to); return; }
    const range = document.createRange(); range.setStart(target.firstChild, from); range.setEnd(target.firstChild, to);
    const selection = document.getSelection(); selection.removeAllRanges(); selection.addRange(range);
  };
  select(titleInput, 0, 7);
  titleInput.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 200, clientY: 100 }));
  const menu = document.querySelector('body > .menu');
  check(!!menu, '属性值右键打开真实菜单');
  const names = [...menu.querySelectorAll('.menu-item-title')].map(el => el.textContent);
  check(names.some(name => /Property type|属性类型/.test(name)), '菜单包含属性类型子菜单');
  for (const term of [/Cut|剪切/, /Copy|复制/, /Paste|粘贴/, /Remove|移除/]) check(names.some(name => term.test(name)), '菜单包含 ' + term);
  const clipboard = require('electron').clipboard;
  const previousClipboard = clipboard.readText();
  const clickMenu = term => [...document.querySelectorAll('body > .menu .menu-item')].find(item => term.test(item.querySelector('.menu-item-title')?.textContent || '')).click();
  try {
    clickMenu(/^(Copy|复制)$/);
    check(clipboard.readText() === 'Changed', '属性菜单复制输入框当前选区到系统剪贴板');
    await wait(50);
    const cutInput = input('title');
    select(cutInput, 0, 7);
    cutInput.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 200, clientY: 100 }));
    clickMenu(/^(Cut|剪切)$/);
    await until(async () => (await diskFm(file)).title === ' via sidebar', '剪切属性选区落盘');
    check((await diskFm(file)).title === ' via sidebar', '属性菜单剪切选区且真实写回');
    await wait(180);
    const pasteInput = input('title');
    select(pasteInput, 0, 0);
    pasteInput.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 200, clientY: 100 }));
    clickMenu(/^(Paste|粘贴)$/);
    await until(async () => (await diskFm(file)).title === 'Changed via sidebar', '粘贴属性选区落盘');
    check((await diskFm(file)).title === 'Changed via sidebar', '属性菜单粘贴选区且真实写回');
  } finally { clipboard.writeText(previousClipboard); }
  await wait(180);
  row('status').querySelector('.metadata-property-icon').click();
  clickMenu(/^(Number|数字)$/);
  await until(() => !!document.querySelector('.modal-container .modal-title'), '不兼容类型转换确认');
  check(types.getAssignedWidget('status') === 'number', '图标菜单选择 Number 类型');
  check((await diskFm(file)).status === 'open', '转换确认前保留原值');
  document.querySelector('.modal-container .modal-close-button').click();
  check((await diskFm(file)).status === 'open', '取消类型转换保留原值');
  await types.unsetType('status');
  await edit('date', '2026-10-22');
  check(types.getTypeInfo('date', '2026-10-22').inferred.type === 'date', '日期编辑器保留日期类型');
  const dateInput = input('date');
  dateInput.value = '2026-10-23'; dateInput.setCustomValidity('Invalid date'); await dateInput.commitMetadata();
  check(dateInput.getAttribute('aria-invalid') === 'true', '无效日期标记错误');
  const date = (await diskFm(file)).date;
  check(date === '2026-10-22' || date?.toISOString?.().startsWith('2026-10-22'), '无效日期不覆盖已存值');
  check((await app.vault.read(file)).includes('# Body remains'), '属性编辑保留笔记正文');
  await app.workspace.openFile(await app.vault.create('Empty properties.md', '# Empty\n'));
  await until(() => view.contentEl.querySelector('.metadata-add-button'), '无属性笔记侧栏显示添加入口');
  check(!!view.contentEl.querySelector('.metadata-add-button'), '无 frontmatter 时侧栏仍能添加首个属性');
  view.contentEl.querySelector('.metadata-add-button').click();
  await until(() => document.querySelector('.modal-container .prompt-input'), '添加属性弹层');
  const newKey = document.querySelector('.modal-container .prompt-input');
  newKey.value = 'first';
  newKey.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
  await until(async () => (await app.vault.read(app.vault.getFileByPath('Empty properties.md'))).includes('first:'), '首个属性落盘');
  check((await app.vault.read(app.vault.getFileByPath('Empty properties.md'))).includes('first:'), '侧栏新增首个属性真实落盘');
  const conversion = await app.vault.create('Conversion.md', '---\nconvert: "42"\nuntouched: keep\n---\n# Convert\n');
  await app.workspace.openFile(conversion);
  await until(() => !!row('convert'), '转换测试属性挂载');
  row('convert').querySelector('.metadata-property-icon').click();
  clickMenu(/^(Number|数字)$/);
  await until(() => !!document.querySelector('.modal-container .modal-button-container .mod-cta'), '类型转换确认按钮');
  document.querySelector('.modal-container .modal-button-container .mod-cta').click();
  await until(async () => (await diskFm(conversion)).convert === 42, '确认转换真实写盘');
  check((await diskFm(conversion)).convert === 42, '确认转换把数值字符串保存为 Number');
  check((await diskFm(conversion)).untouched === 'keep', '类型转换保留其他属性');
  const caseFile = await app.vault.create('CaseProperty.md', '---\nScore: 7\n---\n');
  await until(() => app.metadataCache.getFileCache(caseFile)?.frontmatter?.Score === 7, '大小写属性索引');
  const allLeaf = await app.workspace.ensureSideLeaf('all-properties', 'right', { reveal: true });
  const allView = allLeaf.view;
  const allScore = () => [...allView.contentEl.querySelectorAll('.property-item')].find(item => item.querySelector('.tree-item-inner-text')?.textContent === 'score');
  await until(() => !!allScore(), '全部属性挂载');
  check(allScore().querySelector('.tree-item-flair').textContent === '2', '全部属性按忽略大小写的键汇总出现次数');
  check(!!allScore().querySelector('svg.lucide-binary'), '全部属性图标使用库级 Number 类型');
  allScore().dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 200, clientY: 100 }));
  clickMenu(/^(Text|文本)$/);
  await until(() => !!allScore()?.querySelector('svg.lucide-text'), '全部属性类型图标更新');
  check(types.getAssignedWidget('score') === 'text', '全部属性右键菜单切换库级类型');
  check(!!allScore().querySelector('svg.lucide-text'), '全部属性类型变化刷新图标');
  await types.setType('score', 'number');
  return { pass: true, count: checks.length, checks };
})()
